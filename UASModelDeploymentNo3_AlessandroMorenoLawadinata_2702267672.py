import streamlit as st
import requests

st.set_page_config(page_title="Obesity Prediction", layout="centered")
st.title("Obesity Level Prediction")
st.write("Enter the following data to predict your obesity level:")

# Form Input User
with st.form("obesity_form"):
    Gender = st.selectbox("Gender", ["Male", "Female"])
    Age = st.number_input("Age", min_value=1, max_value=120)
    Height = st.number_input("Height (meter)", min_value=1.0, max_value=2.5)
    Weight = st.number_input("Weight (kg)", min_value=1.0, max_value=250.0)
    family_history_with_overweight = st.selectbox("Family History of Overweight?", ["yes", "no"])
    FAVC = st.selectbox("Frequent consumption of high caloric food (FAVC)?", ["yes", "no"])
    FCVC = st.slider("Vegetable consumption frequency (FCVC)", 1, 3)
    NCP = st.slider("Number of main meals (NCP)", 1, 4)
    CAEC = st.selectbox("Eating between meals (CAEC)", ["no", "Sometimes", "Frequently", "Always"])
    SMOKE = st.selectbox("Do you smoke?", ["yes", "no"])
    CH2O = st.slider("Daily water intake (CH2O)", 1, 3)
    SCC = st.selectbox("Do you monitor your calories?", ["yes", "no"])
    FAF = st.slider("Physical activity frequency (FAF)", 0.0, 3.0, step=0.5)
    TUE = st.slider("Time using technology (TUE)", 0.0, 3.0, step=0.5)
    CALC = st.selectbox("Alcohol consumption (CALC)", ["no", "Sometimes", "Frequently", "Always"])
    MTRANS = st.selectbox("Transportation method", ["Public_Transportation", "Walking", "Automobile", "Motorbike", "Bike"])

    submitted = st.form_submit_button("Predict")

# Prediction
if submitted:
    BMI = Weight / (Height ** 2)
    data = {
        "Gender": Gender,
        "Age": Age,
        "Height": Height,
        "Weight": Weight,
        "family_history_with_overweight": family_history_with_overweight,
        "FAVC": FAVC,
        "FCVC": FCVC,
        "NCP": NCP,
        "CAEC": CAEC,
        "SMOKE": SMOKE,
        "CH2O": CH2O,
        "SCC": SCC,
        "FAF": FAF,
        "TUE": TUE,
        "CALC": CALC,
        "MTRANS": MTRANS,
        "BMI": BMI
    }

    try:
        response = requests.post("http://localhost:8000/predict", json=data)
        if response.status_code == 200:
            prediction = response.json()['prediction']
            st.success(f"Predict Your Obesity Level: **{prediction}**")
        else:
            st.error("An error occurred while processing the prediction.")
    except:
        st.error("Failed to connect to API. Make sure the FastAPI backend is running..")